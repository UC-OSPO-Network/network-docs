#!/usr/bin/env python3
"""Embed the deck font in presentations/_shared/ucospo-theme.scss as base64.

Quarto inlines the theme CSS into each deck as a data: stylesheet. A relative
url(fonts/...) inside it has nothing to resolve against, so the font never
loads. A data: URI inside the stylesheet always works and keeps each deck one
portable file.

The woff2 files in presentations/_shared/fonts/ are the source. After you
change one, run:  python3 scripts/embed_fonts.py
"""

import base64
import pathlib
import re

SHARED = pathlib.Path(__file__).resolve().parent.parent / "presentations" / "_shared"
SCSS = SHARED / "ucospo-theme.scss"
FAMILY = "Atkinson Hyperlegible"
FACES = [(400, "atkinson-hyperlegible-latin-400-normal.woff2"),
         (700, "atkinson-hyperlegible-latin-700-normal.woff2")]

BEGIN = "// fonts:begin (generated by scripts/embed_fonts.py, do not edit by hand)"
END = "// fonts:end"


def block() -> str:
    out = [BEGIN]
    for weight, name in FACES:
        data = base64.b64encode((SHARED / "fonts" / name).read_bytes()).decode()
        out.append(
            "@font-face {\n"
            f'  font-family: "{FAMILY}";\n'
            "  font-style: normal;\n"
            f"  font-weight: {weight};\n"
            f'  src: url("data:font/woff2;base64,{data}") format("woff2");\n'
            "}\n"
        )
    out.append(END)
    return "\n".join(out)


text = SCSS.read_text()
if BEGIN in text:
    new = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), lambda m: block(), text, flags=re.S)
else:
    new = re.sub(r"@font-face \{.*?\}\n\n@font-face \{.*?\}\n", lambda m: block() + "\n", text, count=1, flags=re.S)
    assert new != text, "no @font-face blocks found"
SCSS.write_text(new)
print(f"Embedded {len(FACES)} fonts in {SCSS.relative_to(SHARED.parent.parent)}")
